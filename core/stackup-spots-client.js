/* StackUp Hold'em Grinder EVO — solver transport for SPOTS.
   Production path:
   1) use a configured live solver API when available;
   2) otherwise use the solver-backed static bank generated by GitHub Actions.
   The UI never needs to know which transport supplied the solved spot. */
(function(global){
  'use strict';

  const state={
    current:null,
    loading:false,
    error:null,
    lastAnswer:null,
    source:null,
    manifest:null,
    cursor:0,
    lastStats:null,
    coverageError:null,
    heavyBankDeferred:false
  };

  const cfg=Object.assign({
    enabled:true,
    baseUrl:'',
    staticBase:'data/solver',
    nextPath:'/v1/grinder/spots/next',
    answerPath:'/v1/grinder/spots/answer',
    requestTimeoutMs:12000
  },global.STACKUP_SOLVER_CONFIG||{});

  let staticManifestPromise=null;
  const staticLoads=new Map();
  const staticBank={
    manifest:null,
    preflop:null,
    postflop:null,
    pushfold:null,
    tournament:null,
    reentry:null,
    opponentProfile:null,
    multiwayTournament:null,
    multiwayPostflop:null,
    preflopDecisions:null,
    textureSizing:null,
    preflop9max:null,
    preflopMultistack:null,
    preflopHu:null,
    lineBank:null
  };

  const STATIC_PARTS=Object.freeze({
    preflop:{file:'preflop.json',kind:'array'},
    postflop:{file:'postflop.json',kind:'array'},
    pushfold:{file:'pushfold-hu-v1.json',kind:'pushfold'},
    tournament:{file:'tournament.json',kind:'spots'},
    reentry:{file:'reentry.json',kind:'spots'},
    opponentProfile:{file:'opponent-profile.json',kind:'spots'},
    multiwayTournament:{file:'multiway-tournament.json',kind:'spots'},
    multiwayPostflop:{file:'multiway-postflop.json',kind:'spots'},
    preflopDecisions:{file:'preflop-decisions.json',kind:'spots'},
    textureSizing:{file:'texture-sizing.json',kind:'spots'},
    preflop9max:{file:'preflop-9max.json',kind:'spots'},
    preflopMultistack:{file:'preflop-multistack.json',kind:'spots'},
    preflopHu:{file:'preflop-hu.json',kind:'spots'},
    lineBank:{file:'line-bank.json',kind:'spots'}
  });

  function baseUrl(){
    return String(cfg.baseUrl||global.StackUpGrinder?.config?.apiBase||'').replace(/\/$/,'');
  }

  function hasStaticBank(){
    return cfg.enabled!==false&&!!cfg.staticBase;
  }

  function available(){
    return cfg.enabled!==false&&(!!baseUrl()||hasStaticBank());
  }

  async function fetchJson(url){
    const controller=new AbortController();
    const timer=setTimeout(()=>controller.abort(),cfg.requestTimeoutMs);
    try{
      const res=await fetch(url,{headers:{Accept:'application/json'},signal:controller.signal,cache:'no-store'});
      clearTimeout(timer);
      if(!res.ok)throw new Error('http_'+res.status);
      return res.json();
    }catch(error){
      clearTimeout(timer);
      throw error;
    }
  }

  function staticUrl(file){
    const base=String(cfg.staticBase||'data/solver').replace(/\/$/,'')+'/';
    try{return new URL(base+file,document.baseURI).toString();}
    catch(_){return base+file;}
  }

  function staticPartValid(kind,value){
    if(kind==='array')return Array.isArray(value)&&value.length>0;
    if(kind==='pushfold')return !!(value&&typeof value==='object'&&value.charts);
    if(kind==='spots')return !!(value&&typeof value==='object'&&Array.isArray(value.spots));
    return false;
  }

  async function ensureStaticManifest(){
    if(staticBank.manifest)return staticBank.manifest;
    if(!staticManifestPromise){
      staticManifestPromise=fetchJson(staticUrl('manifest.json')).then(manifest=>{
        staticBank.manifest=manifest;
        state.manifest=manifest;
        return manifest;
      }).catch(error=>{
        staticManifestPromise=null;
        throw error;
      });
    }
    return staticManifestPromise;
  }

  async function loadStaticPart(key){
    if(staticBank[key])return staticBank[key];
    if(staticLoads.has(key))return staticLoads.get(key);
    const spec=STATIC_PARTS[key];
    if(!spec)throw new Error('static_bank_unknown_part:'+key);
    const promise=fetchJson(staticUrl(spec.file)).then(value=>{
      if(!staticPartValid(spec.kind,value))throw new Error('static_'+key+'_invalid');
      staticBank[key]=value;
      staticLoads.delete(key);
      return value;
    }).catch(error=>{
      staticLoads.delete(key);
      throw error;
    });
    staticLoads.set(key,promise);
    return promise;
  }

  function isMobileRuntime(){
    try{
      const ua=String(global.navigator?.userAgent||'');
      return /Android|iPhone|iPad|iPod|Mobile/i.test(ua);
    }catch(_){
      return false;
    }
  }

  function allowStaticPart(key){
    // The multistack monolith is ~81 MB. Parsing it on Android/iOS can lock the
    // WebView main thread long enough to make navigation and SPOTS appear frozen.
    // Mobile uses the smaller solved banks; when they cannot satisfy the strict
    // coverage floor, the UI reports coverage instead of freezing the app.
    if(key==='preflopMultistack'&&isMobileRuntime())return false;
    return true;
  }

  function addPlan(plan,key){
    if(STATIC_PARTS[key]&&allowStaticPart(key)&&!plan.includes(key))plan.push(key);
  }

  function staticLoadPlan(filters){
    const f=filters||{};
    const street=normalizedStreet(f.street);
    const tableSize=Number(f.tableSize);
    const game=String(f.gameType||'').toUpperCase();
    const tournamentish=game==='TOURNAMENT'||!!f.tournamentType||!!f.phase||!!f.fieldSize||!!f.opponentProfile;
    const plan=[];

    // Start with the smallest bank that is most likely to satisfy the active
    // filter. Only add heavier banks when strict coverage is still below floor.
    if(street==='PRE-FLOP'){
      addPlan(plan,'preflop');
      if(tableSize===2){addPlan(plan,'pushfold');addPlan(plan,'preflopHu');}
      addPlan(plan,'preflopDecisions');
      if(tournamentish){
        addPlan(plan,'reentry');
        addPlan(plan,'multiwayTournament');
        addPlan(plan,'opponentProfile');
        addPlan(plan,'tournament');
      }
      if(tableSize===9||tableSize===10)addPlan(plan,'preflop9max');
      else addPlan(plan,'preflop9max');
      // 81 MB monolith: intentionally last. It is never downloaded merely by
      // opening SPOTS and is reached only when smaller strict banks cannot meet
      // the selected coverage floor.
      addPlan(plan,'preflopMultistack');
    }else if(street==='FLOP'||street==='TURN'||street==='RIVER'){
      addPlan(plan,'postflop');
      addPlan(plan,'multiwayPostflop');
      addPlan(plan,'textureSizing');
      addPlan(plan,'lineBank');
      addPlan(plan,'opponentProfile');
      addPlan(plan,'multiwayTournament');
      addPlan(plan,'tournament');
    }else{
      // RANDOM street: postflop is compact and usually clears the strict floor
      // without touching the heavyweight preflop banks.
      addPlan(plan,'postflop');
      addPlan(plan,'preflop');
      addPlan(plan,'preflopDecisions');
      addPlan(plan,'multiwayPostflop');
      addPlan(plan,'textureSizing');
      if(tableSize===2){addPlan(plan,'pushfold');addPlan(plan,'preflopHu');}
      addPlan(plan,'reentry');
      addPlan(plan,'multiwayTournament');
      addPlan(plan,'opponentProfile');
      addPlan(plan,'tournament');
      addPlan(plan,'lineBank');
      addPlan(plan,'preflop9max');
      addPlan(plan,'preflopMultistack');
    }
    return plan;
  }

  function yieldToBrowser(){
    return new Promise(resolve=>setTimeout(resolve,0));
  }

  async function ensureStaticBank(filters){
    await ensureStaticManifest();
    state.heavyBankDeferred=false;
    const sequencer=global.StackUpTrainingSequencer;

    // Legacy fallback needs both classic pools because it chooses by street.
    if(!sequencer?.stats){
      await loadStaticPart('preflop');
      await yieldToBrowser();
      await loadStaticPart('postflop');
      return staticBank;
    }

    const activeFilters=filters||{};
    const plan=staticLoadPlan(activeFilters);
    if(isMobileRuntime()&&!plan.includes('preflopMultistack'))state.heavyBankDeferred=true;
    let lastStats=null;
    let lastError=null;
    for(const key of plan){
      try{
        await loadStaticPart(key);
      }catch(error){
        lastError=error;
        continue;
      }

      // Give touch/navigation events a chance to run between JSON parses.
      await yieldToBrowser();

      try{
        lastStats=sequencer.stats(staticBank,activeFilters);
        state.lastStats=lastStats;
        // On mobile, prioritize first-interaction responsiveness. The sequencer
        // still validates every presented decision; coverage publishability is
        // audited separately and remains visible in state.lastStats.
        if(lastStats.publishable||(isMobileRuntime()&&lastStats.candidates>0))break;
      }catch(error){
        lastError=error;
      }
    }

    if(!lastStats&&lastError)throw lastError;
    return staticBank;
  }

  async function rawRequest(path,{method='GET',body=null}={}){
    const base=baseUrl();
    if(!base)return {ok:false,status:0,error:'solver_api_not_configured'};
    const controller=new AbortController();
    const timer=setTimeout(()=>controller.abort(),cfg.requestTimeoutMs);
    try{
      const headers={'Accept':'application/json','X-StackUp-Product':'grinder'};
      const identity=global.StackUpGrinder?.identity?.get?.();
      if(identity?.token)headers.Authorization='Bearer '+identity.token;
      if(body!==null)headers['Content-Type']='application/json';
      const res=await fetch(base+'/'+String(path||'').replace(/^\//,''),{
        method,headers,body:body===null?undefined:JSON.stringify(body),signal:controller.signal,credentials:'omit'
      });
      clearTimeout(timer);
      let data=null;
      try{data=await res.json();}catch(_){}
      return {ok:res.ok,status:res.status,data};
    }catch(error){
      clearTimeout(timer);
      return {ok:false,status:0,error:error?.name==='AbortError'?'timeout':'network_error'};
    }
  }

  function toQuery(filters){
    const q=new URLSearchParams();
    Object.entries(filters||{}).forEach(([k,v])=>{
      if(v===undefined||v===null||v===''||(Array.isArray(v)&&!v.length))return;
      q.set(k,Array.isArray(v)?v.join(','):String(v));
    });
    return q.toString();
  }

  function clone(value){
    if(global.structuredClone){
      try{return global.structuredClone(value);}catch(_){}
    }
    return JSON.parse(JSON.stringify(value));
  }

  function normalizedStreet(value){
    const s=String(value||'').toUpperCase().replace('PREFLOP','PRE-FLOP');
    return ['PRE-FLOP','FLOP','TURN','RIVER'].includes(s)?s:null;
  }

  function pickStatic(pool,filters){
    let candidates=[...pool];
    const hero=String(filters?.heroPosition||'').toUpperCase();
    if(hero){
      const exact=candidates.filter(s=>String(s?.scenario?.heroPosition||'').toUpperCase()===hero);
      if(exact.length)candidates=exact;
    }
    const stack=Number(filters?.effectiveStack);
    if(Number.isFinite(stack)&&stack>0){
      const exact=candidates.filter(s=>Math.abs(Number(s?.scenario?.effectiveStack)-stack)<0.01);
      if(exact.length)candidates=exact;
    }
    if(!candidates.length)return null;
    const index=state.cursor++%candidates.length;
    const spot=clone(candidates[index]);
    const hands=(spot.strategy||[]).filter(h=>h?.hand&&Array.isArray(h.actions)&&h.actions.length);
    if(hands.length){
      const hand=hands[(state.cursor*17+index*7)%hands.length];
      spot.hand=hand.hand;
      spot.id=String(spot.id||spot.solveId||'solver-spot')+'-'+String(hand.hand);
    }
    if(filters?.gameType)spot.scenario.gameType=filters.gameType;
    return spot;
  }

  async function nextStatic(filters){
    const bank=await ensureStaticBank(filters);
    const sequencer=global.StackUpTrainingSequencer;
    if(sequencer?.pick){
      const activeFilters=filters||{};
      const spot=sequencer.pick(bank,filters||{});
      try{
        const key=sequencer.filterKey(activeFilters);
        if(!state.lastStats||state.lastStats.filterKey!==key)state.lastStats=sequencer.stats(bank,activeFilters);
      }catch(_){state.lastStats=null;}
      if(!spot){
        if(state.lastStats&&!state.lastStats.publishable){
          const err=new Error('scenario_coverage_below_minimum');
          err.coverage=state.lastStats;
          throw err;
        }
        throw new Error('no_solver_spot_for_active_filters');
      }
      return spot;
    }

    // Safety fallback for older cached HTML: deterministic legacy picker is kept
    // only when the V2 sequencer script is unavailable.
    let street=normalizedStreet(filters?.street);
    if(!street){
      const cycle=['PRE-FLOP','FLOP','TURN','RIVER'];
      street=cycle[state.cursor%cycle.length];
    }
    const pool=street==='PRE-FLOP'
      ?bank.preflop
      :bank.postflop.filter(s=>normalizedStreet(s?.scenario?.street)===street);
    return pickStatic(pool.length?pool:bank.preflop,filters||{});
  }

  async function next(filters){
    if(!available())return null;
    state.loading=true;
    state.error=null;
    state.coverageError=null;
    try{
      let spot=null;
      if(baseUrl()){
        const qs=toQuery(filters);
        const res=await rawRequest(cfg.nextPath+(qs?'?'+qs:''),{method:'GET'});
        if(res.ok){
          spot=res.data?.spot||res.data;
          state.source='api';
        }
      }
      if(!spot&&hasStaticBank()){
        spot=await nextStatic(filters||{});
        state.source='static';
      }
      if(!spot)throw new Error('solver_spot_unavailable');
      global.StackUpSpotsEngine?.validateSolverSpot?.(spot);
      const solved=global.StackUpSolvedSpotContract?.validateSolvedDecision?.(spot,spot.hand);
      if(solved&&!solved.ok)throw new Error('unvalidated_solved_spot:'+solved.errors.join(','));
      if(solved?.id){
        spot.solvedSpotId=solved.id;
        spot.validationMode='STRICT_SOLVED_ONLY';
      }
      state.current=spot;
      return spot;
    }catch(error){
      state.error=String(error?.message||error);
      state.coverageError=error?.coverage||null;
      return null;
    }finally{
      state.loading=false;
    }
  }

  async function answer(payload){
    state.lastAnswer=payload||null;
    try{
      const entry={
        ...(payload||{}),
        source:state.source,
        answeredAt:new Date().toISOString()
      };
      const storage=global.StackUpGrinder?.storage;
      storage?.set?.('last_solver_answer',entry);
      const previous=storage?.get?.('solver_answer_history',[]);
      const history=Array.isArray(previous)?previous:[];
      history.push(entry);
      storage?.set?.('solver_answer_history',history.slice(-1000));
    }catch(_){}
    if(baseUrl())return rawRequest(cfg.answerPath,{method:'POST',body:payload||{}});
    return {ok:true,status:200,data:{accepted:true,source:'static'}};
  }

  function setCurrent(spot){
    global.StackUpSpotsEngine?.validateSolverSpot?.(spot);
    const solved=global.StackUpSolvedSpotContract?.validateSolvedDecision?.(spot,spot?.hand);
    if(solved&&!solved.ok)throw new Error('unvalidated_solved_spot:'+solved.errors.join(','));
    if(solved?.id){
      spot.solvedSpotId=solved.id;
      spot.validationMode='STRICT_SOLVED_ONLY';
    }
    state.current=spot;
    state.error=null;
    state.source='manual';
    return spot;
  }

  global.StackUpSpotsClient=Object.freeze({
    config:cfg,
    state,
    available,
    next,
    answer,
    setCurrent,
    preload:ensureStaticBank
  });
})(window);
